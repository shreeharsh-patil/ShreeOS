#!/usr/bin/env bash
set -Eeuo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd -P)"
live="$root/prototype/debian-live/config/includes.chroot/usr/local/sbin/shreeos-live-boot-check"
sddm="$root/prototype/debian-live/profiles/plasma/includes.chroot/usr/local/sbin/shreeos-sddm-live-autologin"
verify="$root/scripts/shreeos-verify-installed"
builder="$root/scripts/build-debian-prototype.sh"
calamares_grub_helper="$root/prototype/debian-live/profiles/desktop/includes.chroot/usr/local/libexec/shreeos-install-bios-grub"
grep -Fq 'if [ ! -e /run/live/medium ]; then' "$live"
grep -Fq 'shreedctl ping' "$live"
grep -Fq 'shree-hardware' "$live"
grep -Fq 'live-config.user-default-groups=' "$builder"
grep -Fq 'shree-hardware' "$builder"
users_conf="$root/prototype/debian-live/profiles/desktop/includes.chroot/etc/calamares/modules/users.conf"
grep -Fq '    - shree-hardware' "$users_conf"
grep -Fq 'rm -f "$override"' "$sddm"
grep -Fq '/boot/grub/grub.cfg' "$verify"
grep -Fq 'SHREEOS_INSTALLED_OK' "$verify"
grep -Fq 'install -Dm0755 \' "$builder"
grep -Fq '"$CONFIG_SOURCE/profiles/desktop/includes.chroot/usr/local/libexec/shreeos-install-bios-grub"' "$builder"
grep -Fq '"$BUILD_DIR/config/includes.chroot/usr/local/libexec/shreeos-install-bios-grub"' "$builder"
grep -Fq 'usr/local/libexec/shreeos-install-bios-grub' "$root/tests/unified/test-iso-contents.sh"
test -s "$calamares_grub_helper"
bash -n "$verify"
sh -n "$live" "$sddm"
echo 'Live-to-installed integration checks passed.'
